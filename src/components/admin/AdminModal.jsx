
import React from "react";
import { X } from "lucide-react";

import FormField from "./FormField";
import ModalActions from "./ModalActions";

function AdminModal({
  modal,
  setModal,

  studentForm,
  setStudentForm,
  addStudent,

  subjectForm,
  setSubjectForm,
  addSubject,
  toggleSubjectAssignment,

  enrollmentForm,
  setEnrollmentForm,
  addEnrollment,

  scoreForm,
  setScoreForm,
  addScore,

  scoreClass,
  scoreDepartment,
  scoreStudents,
  scoreSubjects,
  scoreCA,
  scoreTotal,
  liveGrade,

  departments,
  secondaryClasses,
  enrollmentClassOptions,
  subjectAssignmentOptions,
  requiresDepartment,
}) {
  if (!modal) return null;

  return (
    <div
      className="admin-modal-backdrop"
      onMouseDown={(e) => {
        if (e.target === e.currentTarget) {
          setModal("");
        }
      }}
    >
      <div className="admin-modal">
        <div className="admin-modal-heading">
          <div>
            <span className="admin-eyebrow">
              O'LAK TRIUMPH SCHOOL
            </span>

            <h3>
              {modal === "student"
                ? "Add a student"
                : modal === "subject"
                ? subjectForm.id
                  ? "Edit subject assignments"
                  : "Add a subject"
                : modal === "enrollment"
                ? "Enroll a student"
                : "Submit a score"}
            </h3>
          </div>

          <button
            type="button"
            onClick={() => setModal("")}
            aria-label="Close"
          >
            <X size={20} />
          </button>
        </div>

        {/* ADD STUDENT */}

        {modal === "student" && (
          <form onSubmit={addStudent}>
            <div className="admin-form-two">
              <FormField label="First name">
                <input
                  required
                  value={studentForm.firstName}
                  onChange={(e) =>
                    setStudentForm({
                      ...studentForm,
                      firstName: e.target.value,
                    })
                  }
                  placeholder="Enter first name"
                />
              </FormField>

              <FormField label="Surname">
                <input
                  required
                  value={studentForm.surname}
                  onChange={(e) =>
                    setStudentForm({
                      ...studentForm,
                      surname: e.target.value,
                    })
                  }
                  placeholder="Enter surname"
                />
              </FormField>
            </div>

            <FormField label="Student email">
              <input
                required
                type="email"
                value={studentForm.email}
                onChange={(e) =>
                  setStudentForm({
                    ...studentForm,
                    email: e.target.value,
                  })
                }
                placeholder="student@example.com"
              />
            </FormField>

            <FormField label="Admission number">
              <input
                required
                value={studentForm.admissionNumber}
                onChange={(e) =>
                  setStudentForm({
                    ...studentForm,
                    admissionNumber: e.target.value,
                  })
                }
                placeholder="e.g. SCH2025001"
              />
            </FormField>

            <p className="admin-classification-note">
              The initial login password is generated by
              the backend from the student's surname in
              lowercase. The student should change it
              after their first login.
            </p>

            <FormField label="Class">
              <select
                required
                value={studentForm.className}
                onChange={(e) =>
                  setStudentForm({
                    ...studentForm,
                    className: e.target.value,
                    department: "Science",
                  })
                }
              >
                {secondaryClasses.map((className) => (
                  <option
                    key={className}
                    value={className}
                  >
                    {className}
                  </option>
                ))}
              </select>
            </FormField>

            {requiresDepartment(studentForm.className) && (
              <FormField label="Department">
                <select
                  required
                  value={studentForm.department}
                  onChange={(e) =>
                    setStudentForm({
                      ...studentForm,
                      department: e.target.value,
                    })
                  }
                >
                  {departments.map((department) => (
                    <option
                      key={department}
                      value={department}
                    >
                      {department}
                    </option>
                  ))}
                </select>
              </FormField>
            )}

            <FormField label="Gender">
              <select
                value={studentForm.gender}
                onChange={(e) =>
                  setStudentForm({
                    ...studentForm,
                    gender: e.target.value,
                  })
                }
              >
                <option>Female</option>
                <option>Male</option>
              </select>
            </FormField>

            <ModalActions
              onCancel={() => setModal("")}
              submitLabel="Register student"
            />
          </form>
        )}

        {/* ADD OR EDIT SUBJECT */}

        {modal === "subject" && (
          <form onSubmit={addSubject}>
            <FormField label="Subject name">
              <input
                required={!subjectForm.id}
                disabled={Boolean(subjectForm.id)}
                value={subjectForm.name}
                onChange={(e) =>
                  setSubjectForm({
                    ...subjectForm,
                    name: e.target.value,
                  })
                }
                placeholder="e.g. Mathematics"
              />
            </FormField>

            <FormField label="Subject code">
              <input
                required={!subjectForm.id}
                disabled={Boolean(subjectForm.id)}
                value={subjectForm.code}
                onChange={(e) =>
                  setSubjectForm({
                    ...subjectForm,
                    code: e.target.value.toUpperCase(),
                  })
                }
                placeholder="e.g. MTH"
              />
            </FormField>

            <div className="admin-form-field">
              <span>Assign this subject to classes</span>

              <p className="admin-classification-note">
                Select every class and department that
                should offer this subject.
                <br />
                JSS1–JSS3 and SS1 use general class
                assignments.
                <br />
                Only SS2 and SS3 require departments.
              </p>

              <div
                className="admin-subject-assignment-list"
                style={{
                  display: "grid",
                  gridTemplateColumns:
                    "repeat(auto-fit, minmax(180px, 1fr))",
                  gap: 10,
                  marginTop: 10,
                }}
              >
                {subjectAssignmentOptions.map(
                  (assignment) => {
                    const checked =
                      subjectForm.classAssignments.some(
                        (item) =>
                          item.className ===
                            assignment.className &&
                          (item.department || null) ===
                            (assignment.department || null)
                      );

                    const label = assignment.department
                      ? `${assignment.className} — ${assignment.department}`
                      : assignment.className;

                    return (
                      <label
                        key={`${assignment.className}-${
                          assignment.department || "all"
                        }`}
                        style={{
                          display: "flex",
                          alignItems: "center",
                          gap: 8,
                        }}
                      >
                        <input
                          type="checkbox"
                          checked={checked}
                          onChange={() =>
                            toggleSubjectAssignment(
                              assignment
                            )
                          }
                        />

                        <span>{label}</span>
                      </label>
                    );
                  }
                )}
              </div>

              <p className="admin-classification-note">
                {subjectForm.classAssignments.length}{" "}
                assignment(s) selected.
              </p>
            </div>

            <ModalActions
              onCancel={() => setModal("")}
              submitLabel={
                subjectForm.id
                  ? "Update assignments"
                  : "Save subject"
              }
            />
          </form>
        )}

        {/* ENROLLMENT */}

        {modal === "enrollment" && (
          <form onSubmit={addEnrollment}>
            <FormField label="Student full name">
              <input
                required
                value={enrollmentForm.student}
                onChange={(e) =>
                  setEnrollmentForm({
                    ...enrollmentForm,
                    student: e.target.value,
                  })
                }
                placeholder="Enter student's full name"
              />
            </FormField>

            <FormField label="Class">
              <select
                required
                value={enrollmentForm.className}
                onChange={(e) =>
                  setEnrollmentForm({
                    ...enrollmentForm,
                    className: e.target.value,
                    department: "",
                  })
                }
              >
                {enrollmentClassOptions.map((className) => (
                  <option
                    key={className}
                    value={className}
                  >
                    {className}
                  </option>
                ))}
              </select>
            </FormField>

            {requiresDepartment(
              enrollmentForm.className
            ) && (
              <FormField label="Department">
                <select
                  required
                  value={enrollmentForm.department}
                  onChange={(e) =>
                    setEnrollmentForm({
                      ...enrollmentForm,
                      department: e.target.value,
                    })
                  }
                >
                  <option value="">
                    Select department
                  </option>

                  {departments.map((department) => (
                    <option
                      key={department}
                      value={department}
                    >
                      {department}
                    </option>
                  ))}
                </select>
              </FormField>
            )}

            <FormField label="Term">
              <select
                value={enrollmentForm.term}
                onChange={(e) =>
                  setEnrollmentForm({
                    ...enrollmentForm,
                    term: e.target.value,
                  })
                }
              >
                <option>First Term</option>
                <option>Second Term</option>
                <option>Third Term</option>
              </select>
            </FormField>

            <ModalActions
              onCancel={() => setModal("")}
              submitLabel="Enroll student"
            />
          </form>
        )}

        {/* SUBMIT SCORE */}

        {modal === "score" && (
          <form onSubmit={addScore}>
            <div className="admin-score-class-summary">
              <strong>{scoreClass}</strong>

              {requiresDepartment(scoreClass) && (
                <span>{scoreDepartment} Department</span>
              )}
            </div>

            <FormField label="Student">
              <select
                required
                value={scoreForm.student}
                onChange={(e) =>
                  setScoreForm({
                    ...scoreForm,
                    student: e.target.value,
                    subject: "",
                  })
                }
              >
                <option value="">Select a student</option>

                {scoreStudents.map((student) => (
                  <option
                    key={student.id}
                    value={student.id}
                  >
                    {student.name} (
                    {student.admissionNumber})
                  </option>
                ))}
              </select>
            </FormField>

            <FormField label="Subject">
              <select
                required
                value={scoreForm.subject}
                onChange={(e) =>
                  setScoreForm({
                    ...scoreForm,
                    subject: e.target.value,
                  })
                }
              >
                <option value="">Select a subject</option>

                {scoreSubjects.map((subject) => (
                  <option
                    key={subject.id}
                    value={subject.id}
                  >
                    {subject.name} ({subject.code})
                  </option>
                ))}
              </select>
            </FormField>

            <div className="admin-form-two">
              <FormField label="Academic term">
                <select
                  required
                  value={scoreForm.term}
                  onChange={(e) =>
                    setScoreForm({
                      ...scoreForm,
                      term: e.target.value,
                    })
                  }
                >
                  <option>First Term</option>
                  <option>Second Term</option>
                  <option>Third Term</option>
                </select>
              </FormField>

              <FormField label="Academic year">
                <input
                  required
                  value={scoreForm.academicYear}
                  onChange={(e) =>
                    setScoreForm({
                      ...scoreForm,
                      academicYear: e.target.value,
                    })
                  }
                  placeholder="2025/2026"
                />
              </FormField>
            </div>

            <div className="admin-score-section-heading">
              <strong>CONTINUOUS ASSESSMENT</strong>
              <span>Maximum: 40 marks</span>
            </div>

            <div className="admin-form-two">
              {[
                ["test1", "First test (0–10)"],
                ["test2", "Second test (0–10)"],
                ["test3", "Third test (0–10)"],
                ["assignment", "Assignment (0–10)"],
              ].map(([field, label]) => (
                <FormField label={label} key={field}>
                  <input
                    required
                    type="number"
                    min="0"
                    max="10"
                    step="0.01"
                    value={scoreForm[field]}
                    onChange={(e) =>
                      setScoreForm({
                        ...scoreForm,
                        [field]: e.target.value,
                      })
                    }
                  />
                </FormField>
              ))}
            </div>

            <div className="admin-score-section-heading">
              <strong>EXAMINATION</strong>
              <span>Maximum: 60 marks</span>
            </div>

            <FormField label="Examination score (0–60)">
              <input
                required
                type="number"
                min="0"
                max="60"
                step="0.01"
                value={scoreForm.exam}
                onChange={(e) =>
                  setScoreForm({
                    ...scoreForm,
                    exam: e.target.value,
                  })
                }
              />
            </FormField>

            <FormField label="Manual class position (optional)">
              <input
                type="number"
                min="1"
                step="1"
                value={scoreForm.noInClass}
                onChange={(e) =>
                  setScoreForm({
                    ...scoreForm,
                    noInClass: e.target.value,
                  })
                }
                placeholder="Enter position if manually assigned"
              />
            </FormField>

            <div className="admin-score-calculation">
              <div>
                <span>Continuous assessment</span>
                <strong>{scoreCA.toFixed(2)} / 40</strong>
              </div>

              <div>
                <span>Total score</span>
                <strong>{scoreTotal.toFixed(2)} / 100</strong>
              </div>

              {liveGrade && (
                <>
                  <div>
                    <span>Calculated grade</span>
                    <strong>{liveGrade.grade}</strong>
                  </div>

                  <div>
                    <span>Subject remark</span>
                    <strong>{liveGrade.remark}</strong>
                  </div>
                </>
              )}
            </div>

            <ModalActions
              onCancel={() => setModal("")}
              submitLabel="Save score"
            />
          </form>
        )}
      </div>
    </div>
  );
}

export default AdminModal;
